#!/usr/bin/env python3
"""One harness, four engines. Every timed answer is compared with the Postgres
heap answer for the same state (results/ref_<state>.json) before its time counts.

  bench.py --engine pg|qs|mason|native --state A --mode warm|cold|conc [--only q]
"""
import argparse, datetime, decimal, json, os, statistics, subprocess, sys, threading, time, uuid

Q = "/tmp/qsb"
LOOKUP_ID = open(f"{Q}/results/lookup_id.txt").read().strip() if os.path.exists(f"{Q}/results/lookup_id.txt") else None

QUERIES = [
    ("count_by_status", "SELECT status, count(*) FROM orders GROUP BY status ORDER BY status"),
    ("revenue_by_month_join",
     "SELECT date_trunc('month', o.created_at) AS month, date_trunc('year', c.created_at) AS signup_year, "
     "sum(o.amount) AS revenue FROM orders o JOIN customers c ON c.id = o.customer_id GROUP BY 1, 2 ORDER BY 1, 2"),
    ("pk_lookup", f"SELECT * FROM orders WHERE id = '{LOOKUP_ID}'"),
    ("count_star", "SELECT count(*) FROM orders"),
    ("sum_amount", "SELECT sum(amount) FROM orders"),
    ("month_filter_agg",
     "SELECT count(*), sum(amount) FROM orders WHERE created_at >= timestamptz '2025-06-01 00:00:00+00' "
     "AND created_at < timestamptz '2025-07-01 00:00:00+00'"),
]
CONC_QUERIES = ["count_by_status", "revenue_by_month_join"]


def norm(v):
    if isinstance(v, decimal.Decimal):
        return format(v.normalize(), "f") if v == v.to_integral() else format(v, "f").rstrip("0")
    if isinstance(v, datetime.datetime):
        if v.tzinfo is not None:
            v = v.astimezone(datetime.timezone.utc).replace(tzinfo=None)
        return v.isoformat(sep=" ")
    if isinstance(v, uuid.UUID):
        return str(v)
    if isinstance(v, (dict, list)):
        return json.dumps(v, sort_keys=True, separators=(",", ":"))
    if isinstance(v, str) and v[:1] in "{[":
        try:
            return json.dumps(json.loads(v), sort_keys=True, separators=(",", ":"))
        except Exception:
            return v
    if isinstance(v, float):
        return repr(v)
    return v


def canon(rows):
    return [[norm(v) for v in r] for r in rows]


# ---------------------------------------------------------------- engines
class PgWire:
    def __init__(self, dsn):
        import psycopg
        self.psycopg = psycopg
        self.dsn = dsn

    def connect(self):
        c = self.psycopg.connect(self.dsn, autocommit=True)
        return c

    def run(self, conn, sql):
        cur = conn.execute(sql)
        return cur.fetchall()


class Duck:
    """qs: in-memory DuckDB with views generated by qs-query. native: the file."""

    def __init__(self, kind):
        import duckdb
        self.duckdb = duckdb
        self.kind = kind
        self.viewgen_s = None
        if kind == "qs":
            self.root = self._open_qs()
        else:
            self.root = duckdb.connect(os.environ.get("NATIVE_DB", f"{Q}/native/native.duckdb"), read_only=True)
            self._settings(self.root)

    def _settings(self, c):
        c.execute("SET threads = 3")
        c.execute("SET TimeZone = 'UTC'")
        c.execute("SET default_null_order = 'NULLS_LAST_ON_ASC_FIRST_ON_DESC'")

    def _open_qs(self, sqlfiles=None):
        c = self.duckdb.connect()
        self._settings(c)
        t0 = time.perf_counter()
        for t in ("orders", "customers"):
            if sqlfiles:
                sql = open(sqlfiles[t]).read()
            else:
                p = subprocess.run([f"{Q}/bin/qs-query", "-mirror", f"{Q}/mirror", "-table", f"public.{t}"],
                                   capture_output=True, text=True)
                if p.returncode != 0:
                    raise RuntimeError("qs-query failed: " + p.stderr)
                sql = p.stdout
                tag = os.environ.get("VIEW_TAG")
                if tag:
                    open(f"{Q}/results/viewsql_{tag}_{t}.sql", "w").write(sql)
            c.execute(f"CREATE OR REPLACE VIEW {t} AS {sql}")
        self.viewgen_s = time.perf_counter() - t0
        return c

    def regenerate(self):
        if self.kind == "qs":
            self.root = self._open_qs()

    def connect(self):
        return self.root.cursor()

    def run(self, conn, sql):
        return conn.execute(sql).fetchall()


def engine(name):
    if name == "pg":
        return PgWire(f"host={Q}/sock port=5440 dbname=app user=postgres options='-c timezone=UTC'")
    if name == "mason":
        return PgWire(open(f"{Q}/results/mason_url.txt").read().strip())
    return Duck(name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", required=True)
    ap.add_argument("--state", required=True)
    ap.add_argument("--mode", default="warm")
    ap.add_argument("--only")
    ap.add_argument("--runs", type=int, default=5)
    ap.add_argument("--clients", type=int, default=10)
    ap.add_argument("--reps", type=int, default=3)
    a = ap.parse_args()

    refpath = f"{Q}/results/ref_{a.state}.json"
    ref = json.load(open(refpath)) if os.path.exists(refpath) else {}
    eng = engine(a.engine)
    out = {"engine": a.engine, "state": a.state, "mode": a.mode, "queries": {},
           "at": datetime.datetime.utcnow().isoformat()}
    if getattr(eng, "viewgen_s", None) is not None:
        out["qs_viewgen_plus_create_view_s"] = eng.viewgen_s
    qs = [(n, s) for n, s in QUERIES if (a.only is None or n == a.only)]
    if a.mode == "conc":
        qs = [(n, s) for n, s in qs if n in CONC_QUERIES]

    def check(name, rows):
        got = canon(rows)
        if a.engine == "pg" and name not in ref:
            ref[name] = got
            return True, None
        if got == ref.get(name):
            return True, None
        return False, {"got": got[:5], "want": (ref.get(name) or [])[:5], "got_n": len(got), "want_n": len(ref.get(name) or [])}

    for name, sql in qs:
        r = {"sql": sql}
        try:
            if a.mode in ("warm", "cold"):
                if a.mode == "warm" and hasattr(eng, "regenerate"):
                    eng.regenerate()  # fresh view SQL immediately before each timed batch
                conn = eng.connect()
                times = []
                if a.mode == "warm":
                    rows = eng.run(conn, sql)  # warm-up, untimed
                n = 1 if a.mode == "cold" else a.runs
                ok = True
                for _ in range(n):
                    t0 = time.perf_counter()
                    rows = eng.run(conn, sql)
                    times.append((time.perf_counter() - t0) * 1000)
                    good, diff = check(name, rows)
                    if not good:
                        ok = False
                        r["mismatch"] = diff
                r.update(ok=ok, ms=times, best_ms=min(times), median_ms=statistics.median(times), rows=len(rows))
            else:
                reps = []
                ok = True
                for _ in range(a.reps):
                    if hasattr(eng, "regenerate"):
                        eng.regenerate()
                    conns = [eng.connect() for _ in range(a.clients)]
                    if a.engine in ("pg", "mason"):
                        for c in conns:
                            eng.run(c, "SELECT 1")
                    barrier = threading.Barrier(a.clients + 1)
                    res = [None] * a.clients
                    per = [None] * a.clients

                    def work(i):
                        barrier.wait()
                        t = time.perf_counter()
                        try:
                            res[i] = eng.run(conns[i], sql)
                        except Exception as e:  # recorded verbatim
                            res[i] = e
                        per[i] = (time.perf_counter() - t) * 1000

                    th = [threading.Thread(target=work, args=(i,)) for i in range(a.clients)]
                    for t in th:
                        t.start()
                    barrier.wait()
                    t0 = time.perf_counter()
                    for t in th:
                        t.join()
                    wall = (time.perf_counter() - t0) * 1000
                    for x in res:
                        if isinstance(x, Exception):
                            ok = False
                            r["error"] = f"{type(x).__name__}: {x}"
                        else:
                            good, diff = check(name, x)
                            if not good:
                                ok = False
                                r["mismatch"] = diff
                    reps.append({"all_done_ms": wall, "client_mean_ms": statistics.mean(per), "client_ms": per})
                    for c in conns:
                        try:
                            c.close()
                        except Exception:
                            pass
                r.update(ok=ok, reps=reps, median_all_done_ms=statistics.median(x["all_done_ms"] for x in reps),
                         best_all_done_ms=min(x["all_done_ms"] for x in reps))
        except Exception as e:
            r.update(ok=False, error=f"{type(e).__name__}: {e}")
        out["queries"][name] = r
        brief = {k: (round(v, 2) if isinstance(v, float) else v) for k, v in r.items() if k in
                 ("ok", "best_ms", "median_ms", "median_all_done_ms", "best_all_done_ms", "error", "mismatch")}
        print(a.engine, a.state, a.mode, name, brief, flush=True)

    if a.engine == "pg":
        json.dump(ref, open(refpath, "w"))
    suffix = (f"_{a.only}" if a.only else "") + os.environ.get("RESULT_TAG", "")
    json.dump(out, open(f"{Q}/results/{a.engine}_{a.state}_{a.mode}{suffix}.json", "w"), indent=1)


if __name__ == "__main__":
    main()
